import { afterEach, describe, expect, it, vi } from 'vitest'
import { AudioItems } from './audioItems.ts'

const event = (type: string, item_id = 'a') => ({ type, item_id })
describe('server audio references', () => {
  afterEach(() => vi.useRealTimers())
  it.each([true, false])('waits for stop and commit in either order (%s)', async (commitFirst) => {
    const items = new AudioItems()
    const ref = items.reference('a')
    const result = items.wait(ref, Infinity)
    items.observe(event(commitFirst ? 'input_audio_buffer.committed' : 'input_audio_buffer.speech_stopped'))
    expect(items.status(ref).ready).toBe(false)
    items.observe(event(commitFirst ? 'input_audio_buffer.speech_stopped' : 'input_audio_buffer.committed'))
    expect(await result).toEqual({ ready: true, ref })
  })
  it.each(['conversation.item.created', 'conversation.item.added', 'conversation.item.done'])('accepts confirmed user audio (%s)', (type) => {
    const items = new AudioItems()
    items.observe(event('input_audio_buffer.speech_stopped'))
    items.observe({ type, item: { id: 'a', type: 'message', role: 'user', content: [{ type: 'input_audio' }] } })
    expect(items.status(items.reference('a')).ready).toBe(true)
  })
  it('rejects wrong role/content, deletion and previous session', async () => {
    const items = new AudioItems()
    const ref = items.reference('a')
    items.observe(event('input_audio_buffer.speech_stopped'))
    items.observe(event('input_audio_buffer.committed'))
    items.observe({ type: 'conversation.item.added', item: { id: 'a', role: 'assistant', type: 'message', content: [{ type: 'input_audio' }] } })
    expect(await items.wait(ref, Infinity)).toEqual({ ready: false, reason: 'not-user-audio' })
    items.observe(event('conversation.item.deleted'))
    expect(items.status(ref)).toEqual({ ready: false, reason: 'item-deleted' })
    items.reset()
    expect(items.status(ref)).toEqual({ ready: false, reason: 'session-changed' })
  })
  it('resolves reset/cancel/timeout without retaining waiters', async () => {
    vi.useFakeTimers()
    const items = new AudioItems()
    const reset = items.wait(items.reference('a'), Infinity)
    items.reset()
    expect(await reset).toEqual({ ready: false, reason: 'session-changed' })
    const abort = new AbortController()
    const cancelled = items.wait(items.reference('b'), Infinity, abort.signal)
    abort.abort()
    expect(await cancelled).toEqual({ ready: false, reason: 'cancelled' })
    const timed = items.wait(items.reference('c'), performance.now() + 100)
    await vi.advanceTimersByTimeAsync(100)
    expect(await timed).toEqual({ ready: false, reason: 'ready-timeout' })
  })
  it('bounds metadata and pins the active reference', () => {
    const items = new AudioItems()
    items.observe(event('input_audio_buffer.speech_stopped'))
    items.observe(event('input_audio_buffer.committed'))
    const ref = items.reference('a')
    const release = items.pin(ref)
    for (let i = 0; i < 300; i++) items.observe(event('input_audio_buffer.speech_started', String(i)))
    expect(items.status(ref).ready).toBe(true)
    release()
    items.observe(event('input_audio_buffer.speech_started', 'last'))
    expect(items.status(ref).ready).toBe(false)
  })
})
